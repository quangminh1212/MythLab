/* Kokoro-Vietnamese "web" synthesis worker: the 14-voice kokoro-vi-web model (relingo, Apache-2.0). Same text frontend as
 * kokoro-worker.js (SEA-G2P -> Kokoro token ids), but a different model interface and its own onnxruntime-web 1.30
 * (ort130/): the model card says 1.22 gives silently wrong audio, and it needs the session option disable_quant_qdq=1.
 * Messages in:  {t:'init', id, base, model:ArrayBuffer, config:object, dict:ArrayBuffer, voices:ArrayBuffer[]}  |  {t:'synth', id, text, sid}
 * Messages out: {id, ok:true}  |  {id, pcm:Float32Array, rate}  |  {id, err}
 * Runtime files next to this script (copied / generated by scripts/copy-tts.mjs):
 *   ort130/ort.wasm.min.mjs, ort130/ort-wasm-simd-threaded.{mjs,wasm}   onnxruntime-web 1.30, single thread
 *   kokoro/frontend.js, kokoro/normalize-text.js                  text -> SEA-G2P phonemes -> Kokoro token ids
 *                                                                 (compiled from src/app/player/kokoro/*.ts)
 * Model inputs: input_ids int64[1,T] (with the two 0 pads), ref_s float32[1,256], speed float32[1]; output waveform at 24 kHz.
 * ref_s is row min(n,510)-1 of the speaker's 510x256 float32 voice pack, n = tokens without the two pads.
 */
'use strict';

var ort = null;
var fe = null;
var session = null;
var vocab = null;
var dict = null;
var packs = [];
var chain = Promise.resolve();

var RATE = 24000;
/** The model adds about 200 ms of silence at each end of every call; keep 50 ms of it. */
var KEEP = Math.round(RATE * 0.05);
var QUIET = 0.01;
/** The model is much louder than the Piper voices (rms about 0.20 vs 0.07, peaks past full scale clip). Measured in Chrome with GAIN 0.5: rms 0.093-0.108, peak <= 0.70, no clipping; 0.45 brings it to about 0.09. */
var GAIN = 0.45;
/** The frontend refuses more than 2000 characters; stay well below it. */
var MAX_TEXT = 1200;

async function runtime(base) {
  if (!ort) {
    ort = await import(base + 'ort130/ort.wasm.min.mjs');
    ort.env.wasm.wasmPaths = base + 'ort130/';
    ort.env.wasm.numThreads = 1;
    ort.env.wasm.proxy = false;
  }
  if (!fe) fe = await import(base + 'kokoro/frontend.js');
}

async function init(m) {
  await runtime(m.base);
  if (session) {
    try {
      await session.release();
    } catch (e) {
      /* already gone */
    }
    session = null;
  }
  vocab = m.config.vocab;
  dict = new fe.SeaDictionary(new Uint8Array(m.dict));
  packs = (m.voices || []).map(function (b) { return new Float32Array(b); });
  session = await ort.InferenceSession.create(new Uint8Array(m.model), {
    executionProviders: ['wasm'],
    graphOptimizationLevel: 'all',
    extra: { session: { disable_quant_qdq: '1' } },
  });
}

/** Sentences grouped into pieces of at most MAX_TEXT characters (a longer sentence is cut at spaces). */
function pieces(text) {
  var out = [];
  var cur = '';
  var parts = text.match(/[^.!?…\n]+[.!?…]*\s*/g) || [text];
  parts.forEach(function (p) {
    while (p.length > MAX_TEXT) {
      var cut = p.lastIndexOf(' ', MAX_TEXT);
      if (cut < MAX_TEXT / 2) cut = MAX_TEXT;
      if (cur) out.push(cur), (cur = '');
      out.push(p.slice(0, cut));
      p = p.slice(cut);
    }
    if (cur.length + p.length > MAX_TEXT) out.push(cur), (cur = '');
    cur += p;
  });
  if (cur) out.push(cur);
  return out.filter(function (x) { return x.trim(); });
}

function trim(pcm) {
  var a = 0;
  var b = pcm.length;
  while (a < b && Math.abs(pcm[a]) < QUIET) a++;
  while (b > a && Math.abs(pcm[b - 1]) < QUIET) b--;
  return pcm.subarray(Math.max(0, a - KEEP), Math.min(pcm.length, b + KEEP));
}

/** Style row of a voice pack for an utterance of n tokens (the pack has 510 rows of 256 floats). */
function ref(pack, n) {
  var row = Math.max(0, Math.min(n, 510) - 1);
  return pack.slice(row * 256, row * 256 + 256);
}

async function synth(m) {
  if (!session) throw new Error('Giọng Kokoro chưa nạp');
  var pack = packs[Number(m.sid) | 0] || packs[0];
  if (!pack) throw new Error('Thiếu gói giọng Kokoro');
  var parts = [];
  var total = 0;
  var texts = pieces(String(m.text || ''));
  for (var t = 0; t < texts.length; t++) {
    var chunks = fe.phonemizeChunks(texts[t], dict, vocab).chunks;
    for (var i = 0; i < chunks.length; i++) {
      var tokens = chunks[i].tokens;
      var out = await session.run({
        input_ids: new ort.Tensor('int64', BigInt64Array.from(tokens, function (x) { return BigInt(x); }), [1, tokens.length]),
        speed: new ort.Tensor('float32', Float32Array.from([1]), [1]),
        ref_s: new ort.Tensor('float32', ref(pack, tokens.length - 2), [1, 256]),
      });
      var pcm = trim(Float32Array.from(out.waveform.data));
      for (var g = 0; g < pcm.length; g++) pcm[g] *= GAIN;
      parts.push(pcm);
      total += pcm.length;
    }
  }
  var all = new Float32Array(total);
  var at = 0;
  parts.forEach(function (p) {
    all.set(p, at);
    at += p.length;
  });
  return { pcm: all, rate: RATE };
}

self.onmessage = function (e) {
  var m = e.data;
  chain = chain.then(async function () {
    try {
      if (m.t === 'init') {
        await init(m);
        self.postMessage({ id: m.id, ok: true });
      } else if (m.t === 'synth') {
        var r = await synth(m);
        self.postMessage({ id: m.id, pcm: r.pcm, rate: r.rate }, [r.pcm.buffer]);
      }
    } catch (err) {
      self.postMessage({ id: m.id, err: String((err && err.message) || err) });
    }
  });
};
