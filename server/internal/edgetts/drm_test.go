package edgetts

import "testing"

// Vectors produced by generate_sec_ms_gec_v2 of edge-tts 7.3.1 run from
// the reference Python package (1700000000, 1795140000 and 1795140299 are the vectors
// of apps-spec 6.4; 1800000000 was generated as 1800000000.5).
func TestSecMSGECVectors(t *testing.T) {
	cases := []struct {
		unix int64
		want string
	}{
		{0, "52BC7A17B50DFEC9-28C4394775C8751CD2F6859C030C06DB1489ACAB3B3A7651831FC26895177ED6"},
		{1, "52BC7A17B50DFEC9-28C4394775C8751CD2F6859C030C06DB1489ACAB3B3A7651831FC26895177ED6"},
		{299, "52BC7A17B50DFEC9-28C4394775C8751CD2F6859C030C06DB1489ACAB3B3A7651831FC26895177ED6"},
		{300, "F7535A20A262E331-28675BF85C7106BBF20035A78FCB0B6890813EAD5C3B983EF3424931B720BABB"},
		{946684800, "41A43A492D549652-24643F6BF1CF643EF8271B970DB1E914BE86F0C606C9A8699B3F8D086CBEC87A"},
		{1700000000, "2CD23A2CA0B2595A-F3C846C370E05F9CC83ACC5F995C5F5D87A4D0F14CE8936A0F902E64099E38A2"},
		{1763596800, "C6E25F5BA740FA3B-C39E071F750CF70758D0FF9DBDDAB757455C2493BF553090BBE6E8F987E3AB9D"},
		{1795140000, "ADA11D10603509AA-39F4296838CB6C52FD477A211AD0454EE4FABC91CACC3845BAAEAFBBEDBFD07C"},
		{1795140299, "ADA11D10603509AA-39F4296838CB6C52FD477A211AD0454EE4FABC91CACC3845BAAEAFBBEDBFD07C"},
		{1795140300, "F3DE793FAE8E8691-C59A069493EF45954BAA013128D28EA954D8665F73EA680917E783339D93209A"},
		{1800000000, "99E54519B490BE5C-E162DB0977FBDCB9B86DD8148BF1BCDC3C0303176CE39852A42B415935C20654"},
		{2000000000, "2D62557F1142BC5D-FD9C30C68FF194A5EE6B45FEFC5E2BA1D1239F88A90569AB55CFFFAA7799F40E"},
		{4102444800, "DD230DB44FEE2FD7-DA0D4FA797866E36C992FABB81DD2F9DB37EB74D675D63228277003DCD3F9F8C"},
	}
	for _, c := range cases {
		if got := secMSGEC(c.unix); got != c.want {
			t.Errorf("secMSGEC(%d) = %s, want %s", c.unix, got, c.want)
		}
	}
}

func TestSecMSGECShape(t *testing.T) {
	got := secMSGEC(1795140123)
	if len(got) != 16+1+64 || got[16] != '-' {
		t.Fatalf("unexpected token shape %q", got)
	}
}
