def vi_words(text: str) -> int:
    pi = text.find("「Hệ thống")
    body = text[:pi] if pi > 0 else text
    return len([w for w in body.split() if len(w) >= 2])


def main() -> None:
    t = TEXT.replace("\r\n", "\n")
    if not t.endswith("\n"):
        t += "\n"
    OUT.write_text(t, encoding="utf-8")
    print("wrote", OUT)
    print("vi", vi_words(t), "words", len(t.split()), "chars", len(t))
    assert "GHI NHẬN ch.27" in t
    assert "1984" in t
    assert "1,530" in t
    assert vi_words(t) >= 3000, vi_words(t)


if __name__ == "__main__":
    main()
